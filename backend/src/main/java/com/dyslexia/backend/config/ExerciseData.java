    // =========================================================
    // GENERIC JSON
    // =========================================================

    private String json(
            String question,
            String value,
            String correct,
            String wrong1,
            String wrong2,
            String correctAnswer
    ) {

        List<String> options = new ArrayList<>();

        options.add(correct);
        options.add(wrong1);
        options.add(wrong2);
        options.add(value);

        /*
         * distinct().toList() враќа immutable листа.
         * Затоа повторно правиме ArrayList.
         */
        options = new ArrayList<>(
                options.stream()
                        .distinct()
                        .toList()
        );

        String[] fallbacks = {
                "МА",
                "СО",
                "ТА",
                "КО",
                "ЛА",
                "ПО",
                "МО"
        };

        int fallbackIndex = 0;

        while (
                options.size() < 4
                        && fallbackIndex < fallbacks.length
        ) {

            String fallback =
                    fallbacks[fallbackIndex];

            if (!options.contains(fallback)) {
                options.add(fallback);
            }

            fallbackIndex++;
        }

        Collections.shuffle(options);

        return """
                {
                  "question": "%s",
                  "options": ["%s", "%s", "%s", "%s"],
                  "correctAnswer": "%s"
                }
                """.formatted(
                escape(question.formatted(value)),
                escape(options.get(0)),
                escape(options.get(1)),
                escape(options.get(2)),
                escape(options.get(3)),
                escape(correctAnswer)
        );
    }

    // =========================================================
    // ESCAPE JSON
    // =========================================================

    private String escape(String value) {

        if (value == null) {
            return "";
        }

        return value
                .replace("\\", "\\\\")
                .replace("\"", "\\\"");
    }

